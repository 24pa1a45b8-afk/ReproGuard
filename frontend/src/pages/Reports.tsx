import { useState, useEffect } from 'react';
import { Download, FileText } from 'lucide-react';
import { Btn, Page, SectionLabel, Stat, Tag, Th, statusTone } from '../components/ui';
import { runAudit } from '../services/api';
import type { AuditReport } from '../types';

export default function Reports() {
  const [report, setReport] = useState<AuditReport | null>(null);

  const loadReport = () => {
    runAudit("exp-baseline").then(res => setReport(res.data));
  };

  useEffect(() => {
    loadReport();
    const handler = () => loadReport();
    window.addEventListener('dataset-changed', handler);
    return () => window.removeEventListener('dataset-changed', handler);
  }, []);

  const datasetName = report?.summary?.dataset_name || report?.active_dataset?.name || 'Active Dataset';
  const datasetSlug = datasetName.toLowerCase().replace(/[^a-z0-9]/g, '_');

  const generateHumanReadableReport = (rep: AuditReport): string => {
    const dName = rep.summary.dataset_name || rep.active_dataset?.name || 'Active Dataset';
    const targetCol = rep.active_dataset?.target_column || 'Target';
    const rows = rep.active_dataset?.rows ? rep.active_dataset.rows.toLocaleString() : 'N/A';
    const cols = rep.active_dataset?.columns ? `${rep.active_dataset.columns.length} features (${rep.active_dataset.columns.join(', ')})` : 'N/A';
    const filename = rep.active_dataset?.filename || 'wine.csv';
    const hash = rep.summary.dataset_hash || 'N/A';
    
    const separator = "=".repeat(80);
    const subSeparator = "-".repeat(80);

    let text = `${separator}\n`;
    text += `         REPROGUARD™ SCIENTIFIC REPRODUCIBILITY AUDIT REPORT\n`;
    text += `           "Trust Every Experiment. Reproduce Every Result."\n`;
    text += `${separator}\n\n`;

    text += `1. EXECUTIVE DOSSIER\n`;
    text += `${subSeparator}\n`;
    text += `Audit ID             : ${rep.audit_id}\n`;
    text += `Audit Timestamp      : ${new Date(rep.timestamp).toLocaleString()} (${rep.timestamp})\n`;
    text += `Audited Dataset      : ${dName}\n`;
    text += `Source Filename      : ${filename}\n`;
    text += `Cryptographic Hash   : ${hash} (MD5)\n`;
    text += `Dataset Dimensions   : ${rows} rows | ${cols}\n`;
    text += `Target Column        : ${targetCol}\n`;
    text += `Model Evaluated      : RandomForestClassifier (n_estimators=100, max_depth=8, seed=42)\n`;
    text += `Software Environment : Python ${rep.summary.python_version} | DVC ML Pipeline Engine\n\n`;

    text += `2. REPRODUCIBILITY VERIFICATION VERDICT\n`;
    text += `${subSeparator}\n`;
    text += `Overall Status       : [${rep.overall_status}]\n`;
    text += `Verification Summary : ${rep.summary.pass_count} Passed, ${rep.summary.warning_count} Warnings, ${rep.summary.fail_count} Failed (Total ${rep.summary.total_checks} checks)\n`;
    text += `Evaluation Accuracy  : ${(rep.summary.accuracy * 100).toFixed(2)}% (${rep.summary.accuracy.toFixed(4)})\n`;
    text += `Evaluation ROC-AUC   : ${rep.summary.roc_auc.toFixed(4)}\n`;
    text += `Reference Baseline   : Certified UCI Wine Quality Benchmark (Accuracy: 78.44%, ROC-AUC: 0.8748)\n\n`;

    text += `3. DETAILED VERIFIED CHECKS & EVIDENCE\n`;
    text += `${subSeparator}\n`;
    rep.findings.forEach((f, idx) => {
      const tag = f.status === 'PASS' ? '[PASS]' : f.status === 'WARNING' ? '[WARN]' : '[FAIL]';
      text += `${idx + 1}. ${tag} Category: ${f.category} — ${f.name}\n`;
      text += `   Status     : ${f.status}\n`;
      text += `   Explanation: ${f.explanation}\n`;
      text += `   Evidence   : ${f.evidence}\n`;
      if (f.action) {
        text += `   Action     : ${f.action}\n`;
      }
      text += `\n`;
    });

    if (rep.recommendations && rep.recommendations.length > 0) {
      text += `4. REPRODUCIBILITY RECOMMENDATIONS\n`;
      text += `${subSeparator}\n`;
      rep.recommendations.forEach((rec, idx) => {
        text += `   [${idx + 1}] ${rec}\n`;
      });
      text += `\n`;
    }

    text += `${separator}\n`;
    text += `Report generated by ReproGuard Machine Learning Audit Framework\n`;
    text += `Dataset Vault Target: ${dName} (${filename})\n`;
    text += `Repository Reference: HelloJahid/dvc-ml-pipeline\n`;
    text += `${separator}\n`;

    return text;
  };

  const handleDownloadJSON = () => {
    if (!report) return;
    const blob = new Blob([JSON.stringify(report, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `ReproGuard-Audit-${datasetSlug}-${report.audit_id}.json`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  const handleDownloadText = () => {
    if (!report) return;
    const content = generateHumanReadableReport(report);
    const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `ReproGuard-Audit-${datasetSlug}-${report.audit_id}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <Page
      title="Audit reports"
      hint={report ? `${datasetName} · audit ${report.audit_id}` : 'Evidence-backed reproducibility report'}
      actions={
        report && (
          <>
            <Btn onClick={handleDownloadJSON}>
              <Download className="w-3.5 h-3.5 mr-1.5 text-muted" />
              JSON
            </Btn>
            <Btn variant="primary" onClick={handleDownloadText}>
              <FileText className="w-3.5 h-3.5 mr-1.5" />
              Download report (.txt)
            </Btn>
          </>
        )
      }
    >
      {report && (
        <>
          {/* Summary strip */}
          <div className="grid grid-cols-2 lg:grid-cols-4">
            <Stat
              label="Verdict"
              value={<Tag tone={statusTone(report.overall_status)}>{report.overall_status}</Tag>}
              sub={`${report.summary.pass_count} of ${report.summary.total_checks} checks passed`}
            />
            <Stat label="Dataset" value={datasetName} sub={new Date(report.timestamp).toLocaleString()} />
            <Stat
              label="Dataset fingerprint"
              value={
                <span className="font-mono text-sm" title={report.summary.dataset_hash}>
                  {report.summary.dataset_hash.slice(0, 16)}…
                </span>
              }
              sub="md5"
            />
            <Stat label="Model" value="RandomForestClassifier" sub={`audit ${report.audit_id}`} />
            <Stat label="Accuracy" value={<span className="tabular-nums">{report.summary.accuracy.toFixed(4)}</span>} />
            <Stat label="ROC-AUC" value={<span className="tabular-nums">{report.summary.roc_auc.toFixed(4)}</span>} />
            <Stat label="Warnings" value={<span className="tabular-nums">{report.summary.warning_count}</span>} />
            <Stat label="Failures" value={<span className="tabular-nums">{report.summary.fail_count}</span>} />
          </div>

          {/* Findings */}
          <SectionLabel count={report.findings.length}>Audit checks and evidence</SectionLabel>
          <div className="overflow-x-auto">
            <table className="sheet">
              <thead>
                <tr>
                  <th className="rn"></th>
                  <Th>check</Th>
                  <Th>category</Th>
                  <Th>explanation</Th>
                  <Th>evidence</Th>
                  <Th>result</Th>
                </tr>
              </thead>
              <tbody>
                {report.findings.map((finding, idx) => (
                  <tr key={finding.name}>
                    <td className="rn">{idx + 1}</td>
                    <td className="font-medium">{finding.name}</td>
                    <td className="text-muted">{finding.category}</td>
                    <td className="wrap text-xs text-muted min-w-[260px]">{finding.explanation}</td>
                    <td className="wrap font-mono text-xs break-words min-w-[260px]">{finding.evidence}</td>
                    <td><Tag tone={statusTone(finding.status)}>{finding.status}</Tag></td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </>
      )}
    </Page>
  );
}
